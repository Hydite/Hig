export type I18nKey = keyof typeof en;

export function resolveLanguage(preference: LanguagePreference, systemLanguage = navigator.language): ResolvedLanguage {
  if (preference === "en" || preference === "zh-CN") return preference;
  return systemLanguage.toLowerCase().startsWith("zh") ? "zh-CN" : "en";
}

export function createTranslator(preference: LanguagePreference, systemLanguage?: string) {
  const language = resolveLanguage(preference, systemLanguage);
  const dictionary = language === "zh-CN" ? zh : en;
  return {
    language,
    t(key: I18nKey, params: Record<string, string | number> = {}) {
      const template = dictionary[key] ?? en[key] ?? key;
      return template.replace(/\{(\w+)\}/g, (_, name: string) => String(params[name] ?? `{${name}}`));
    },
    error(code: string | undefined, fallback?: string) {
      const normalized = code?.replace(/-/g, "_").toLowerCase();
      const key = normalized ? (`error.${normalized}` as I18nKey) : "error.fallback";
      if (key in dictionary) return dictionary[key];
      if (fallback) return dictionary["error.unknownPrefix"].replace("{message}", fallback);
      return dictionary["error.fallback"];
    }
  };
}

